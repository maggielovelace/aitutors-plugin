// Writes lib/messages.js from _locales/*/messages.json.
//
// chrome.i18n always answers in Chrome's own language and cannot be switched
// at runtime, but D36 puts an English / 简体中文 switch on the options page. So
// the same catalogs are also bundled as a script that the popup, the options
// page and the YouTube content script read through lib/i18n.js. Bundled, not
// loaded at runtime: the extension makes no request of any kind.
//
// Run after editing a messages.json:  node scripts/build-messages.mjs
// tests/messages.test.mjs fails when lib/messages.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const LANGS = ['en', 'zh_CN'];

export function renderMessages() {
  const all = {};
  for (const lang of LANGS) {
    all[lang] = JSON.parse(readFileSync(join(ROOT, '_locales', lang, 'messages.json'), 'utf8'));
  }
  return (
    '// GENERATED by scripts/build-messages.mjs from _locales/*/messages.json. Do not edit.\n' +
    '(function (root) {\n' +
    `  var MESSAGES = ${JSON.stringify(all, null, 2).replace(/\n/g, '\n  ')};\n` +
    '  root.HeddyMessages = MESSAGES;\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = MESSAGES;\n" +
    '})(globalThis);\n'
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(ROOT, 'lib', 'messages.js'), renderMessages());
  console.log('lib/messages.js written');
}
