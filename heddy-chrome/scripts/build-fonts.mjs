// Writes lib/font-data.js from fonts/*.woff2.
//
// The popup and the options page load Manrope with @font-face from fonts/
// (their own origin). The toasts, trays and the YouTube bar live in shadow
// roots on the page, where a chrome-extension:// font URL would need a
// web_accessible_resources entry: a file any page can probe for, which tells
// it Heddy is installed. Instead the same woff2 bytes ship inside the content
// scripts as base64 and lib/fonts.js registers them with new FontFace(bytes):
// no URL, no request, nothing for a page to probe.
//
// Run after changing a file in fonts/:  node scripts/build-fonts.mjs
// tests/fonts.test.mjs fails when lib/font-data.js is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Google Fonts' latin and latin-ext subsets of Manrope (variable, 500–800),
// with their unicode-range, so Siobhán and Zoë render in Manrope too. CJK
// falls through to the system font, as before.
export const FACES = [
  {
    file: 'fonts/manrope-latin.woff2',
    unicodeRange: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
  },
  {
    file: 'fonts/manrope-latin-ext.woff2',
    unicodeRange: 'U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C4, U+2113, U+2C60-2C7F, U+A720-A7FF',
  },
];

// The desk's two other faces (Round 11; the artifact's <link>: JetBrains Mono
// for stamps, labels and counts, Source Serif 4 for quotes and titles), latin
// only, under families of our own. They ship only in the YouTube content
// scripts (lib/font-desk-data.js), so no other page carries their bytes.
const LATIN = FACES[0].unicodeRange;
export const DESK_FACES = [
  { file: 'fonts/jetbrains-mono-latin.woff2', family: 'Heddy Mono', weight: '500 700', unicodeRange: LATIN },
  { file: 'fonts/source-serif-4-latin.woff2', family: 'Heddy Serif', weight: '500 600', unicodeRange: LATIN },
];

export function renderDeskFontData() {
  const faces = DESK_FACES.map((f) => ({ ...f, base64: readFileSync(join(ROOT, f.file)).toString('base64') }));
  return (
    '// GENERATED by scripts/build-fonts.mjs from fonts/*.woff2. Do not edit.\n' +
    '// JetBrains Mono (fonts/OFL-JetBrainsMono.txt) and Source Serif 4\n' +
    '// (fonts/OFL-SourceSerif4.txt), SIL Open Font License 1.1.\n' +
    '(function (root) {\n' +
    `  var FACES = ${JSON.stringify(faces, null, 2).replace(/\n/g, '\n  ')};\n` +
    '  root.HeddyDeskFontData = FACES;\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = FACES;\n" +
    "  else if (root.HeddyFonts && typeof document !== 'undefined') root.HeddyFonts.add(document, FACES);\n" +
    '})(globalThis);\n'
  );
}

export function renderFontData() {
  const faces = FACES.map((f) => ({
    file: f.file,
    unicodeRange: f.unicodeRange,
    base64: readFileSync(join(ROOT, f.file)).toString('base64'),
  }));
  return (
    '// GENERATED by scripts/build-fonts.mjs from fonts/*.woff2. Do not edit.\n' +
    '// Manrope, SIL Open Font License 1.1 (fonts/OFL.txt).\n' +
    '(function (root) {\n' +
    `  var FACES = ${JSON.stringify(faces, null, 2).replace(/\n/g, '\n  ')};\n` +
    '  root.HeddyFontData = FACES;\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = FACES;\n" +
    '})(globalThis);\n'
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(ROOT, 'lib', 'font-data.js'), renderFontData());
  writeFileSync(join(ROOT, 'lib', 'font-desk-data.js'), renderDeskFontData());
  console.log('lib/font-data.js and lib/font-desk-data.js written');
}
